import os
import sys
import json

try:
    from .rules import RuleEngine
    from .planner_llm import PlannerLLM

except ImportError:
    # Allow running this module directly with:
    # python retrieval/planner.py

    sys.path.insert(
        0,
        os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    )

    from retrieval.rules import RuleEngine
    from retrieval.planner_llm import PlannerLLM


class RetrievalPlanner:
    """
    Creates a retrieval plan from the tasks generated by the Mediator.
    """

    def __init__(self, max_workers=2):

        # Rule Engine
        self.rule_engine = RuleEngine()

        # Planner LLM.
        #
        # max_workers controls how many low-confidence tasks are
        # sent to the Planner LLM concurrently in create_plan()'s
        # batched pass. This must not exceed the Ollama server's
        # actual concurrent slot capacity (OLLAMA_NUM_PARALLEL) or
        # requests just queue behind each other with no data on the
        # socket, the same class of issue that caused the
        # WinError 10060 timeout fixed in the Executor. Kept as a
        # constructor argument, set from a single constant in
        # main.py, rather than hardcoded here, so it's easy to tune
        # alongside the Executor's own max_workers in one place.
        self.planner_llm = PlannerLLM(max_workers=max_workers)

        # Confidence Threshold
        self.CONFIDENCE_THRESHOLD = 0.70

    def create_plan(self, tasks):

        # Indexed by position in `tasks` so results can be
        # reassembled in original order regardless of which path
        # (rule engine vs. batched LLM) produced them, and so
        # skipped tasks (retrieval not required) leave no gap.
        retrieval_plan = [None] * len(tasks)

        # Tasks that fall through to the Planner LLM are collected
        # here instead of being classified immediately. Calling the
        # LLM one task at a time meant every low-confidence task
        # blocked on its own full Ollama round-trip before the next
        # one could even start; batching lets plan_batch() run them
        # concurrently instead.
        llm_pending_indices = []
        llm_pending_tasks = []

        # --------------------------------------------------
        # Pass 1: Rule Engine classification (fast, local, no
        # network I/O) — safe to keep sequential.
        # --------------------------------------------------

        for index, task in enumerate(tasks):

            # Skip tasks that don't require retrieval
            if not task["retrieval"]["required"]:
                continue

            classification = self.rule_engine.classify(task["task"])

            # Use Rule Engine for known domains.
            # Otherwise defer to the Planner LLM, batched below.
            if classification["confidence"] >= self.CONFIDENCE_THRESHOLD:

                retrieval_plan[index] = {
                    "task_id": task["task_id"],
                    "task": task["task"],
                    "knowledge_type": classification["knowledge_type"],
                    "query": task["task"],
                    "priority": task["priority"],
                    "planner": "rule_engine"
                }

            else:

                llm_pending_indices.append(index)
                llm_pending_tasks.append(task)

        # --------------------------------------------------
        # Pass 2: everything that needs the Planner LLM runs in
        # one concurrent batch call instead of sequential blocking
        # calls.
        # --------------------------------------------------

        if llm_pending_tasks:

            llm_outputs = self.planner_llm.plan_batch(
                [task["task"] for task in llm_pending_tasks]
            )

            for task, llm_output, index in zip(
                llm_pending_tasks,
                llm_outputs,
                llm_pending_indices
            ):

                try:
                    llm_plan = json.loads(llm_output)

                except json.JSONDecodeError:

                    llm_plan = {
                        "knowledge_type": "unknown",
                        "query": task["task"]
                    }

                retrieval_plan[index] = {
                    "task_id": task["task_id"],
                    "task": task["task"],
                    "knowledge_type": llm_plan.get("knowledge_type", "unknown"),
                    "query": llm_plan.get("query", task["task"]),
                    "priority": task["priority"],
                    "planner": "planner_llm"
                }

        # Drop the placeholders left by tasks that didn't require
        # retrieval, preserving the relative order of the rest.
        return [entry for entry in retrieval_plan if entry is not None]